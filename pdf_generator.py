from fpdf import FPDF
from datetime import datetime

class IOCLReportPDF(FPDF):
    def header(self):
        # Header title (IOCL Brand Colors: Navy Blue & Dark Orange)
        self.set_fill_color(0, 51, 102)  # Navy Blue
        self.rect(0, 0, 210, 28, 'F')
        
        self.set_font("Arial", "B", 16)
        self.set_text_color(255, 255, 255)
        self.cell(0, 10, "IOCL REFINERY - FUEL QUALITY & GCV AUDIT REPORT", ln=True, align="C")
        
        self.set_font("Arial", "", 10)
        self.cell(0, 6, "Boiler & Coal Gasification Unit | AI-Powered Proximate Analysis", ln=True, align="C")
        self.ln(10)

    def footer(self):
        self.set_y(-15)
        self.set_font("Arial", "I", 8)
        self.set_text_color(128, 128, 128)
        self.cell(0, 10, f"Generated by IOCL AI Quality Monitor | Page {self.page_no()}", align="C")

def generate_sample_pdf(moisture, ash, vm, fc, sulfur, predicted_gcv, grade, blending_note):
    pdf = IOCLReportPDF()
    pdf.add_page()
    pdf.set_auto_page_break(auto=True, margin=15)

    # Report metadata
    pdf.set_text_color(0, 0, 0)
    pdf.set_font("Arial", "B", 11)
    timestamp = datetime.now().strftime("%d-%b-%Y %I:%M %p")
    pdf.cell(100, 8, f"Report Date & Time: {timestamp}", ln=False)
    pdf.cell(0, 8, "Unit: Boiler / Gasifier Plant-1", ln=True, align="R")
    pdf.line(10, 38, 200, 38)
    pdf.ln(6)

    # 1. Sample Parameters Table
    pdf.set_font("Arial", "B", 12)
    pdf.set_fill_color(230, 240, 255)
    pdf.cell(0, 9, " 1. Input Proximate & Ultimate Analysis Parameters", ln=True, fill=True)
    pdf.ln(3)

    params = [
        ("Moisture (%)", f"{moisture:.2f} %"),
        ("Ash Content (%)", f"{ash:.2f} %"),
        ("Volatile Matter (%)", f"{vm:.2f} %"),
        ("Calculated Fixed Carbon (%)", f"{fc:.2f} %"),
        ("Sulfur Content (%)", f"{sulfur:.2f} %")
    ]

    pdf.set_font("Arial", "", 11)
    for label, val in params:
        pdf.cell(110, 8, f"  {label}", border=1)
        pdf.cell(80, 8, f"  {val}", border=1, ln=True)

    pdf.ln(8)

    # 2. AI Prediction & Quality Assessment
    pdf.set_font("Arial", "B", 12)
    pdf.set_fill_color(230, 240, 255)
    pdf.cell(0, 9, " 2. AI Prediction & Operational Quality Assessment", ln=True, fill=True)
    pdf.ln(4)

    pdf.set_font("Arial", "B", 13)
    pdf.set_text_color(204, 85, 0)  # Dark Orange highlight
    pdf.cell(0, 10, f"Predicted Gross Calorific Value (GCV): {predicted_gcv:.2f} kcal/kg", ln=True)

    pdf.set_font("Arial", "B", 11)
    if "Grade A" in grade:
        pdf.set_text_color(0, 102, 51)
    else:
        pdf.set_text_color(180, 0, 0)
    pdf.cell(0, 8, f"Operational Classification: {grade}", ln=True)
    pdf.ln(4)

    # 3. Blending & Engineering Recommendation
    pdf.set_text_color(0, 0, 0)
    pdf.set_font("Arial", "B", 12)
    pdf.set_fill_color(230, 240, 255)
    pdf.cell(0, 9, " 3. Blending & Control Room Recommendation", ln=True, fill=True)
    pdf.ln(3)

    pdf.set_font("Arial", "", 11)
    pdf.multi_cell(0, 7, blending_note)
    pdf.ln(15)

    # Signature block
    pdf.set_font("Arial", "I", 10)
    pdf.cell(95, 8, "__________________________", ln=False)
    pdf.cell(95, 8, "__________________________", ln=True, align="R")
    pdf.cell(95, 6, "Shift Control Room Operator", ln=False)
    pdf.cell(95, 6, "Quality Control Engineer (Lab)", ln=True, align="R")

    # Return PDF as bytes so Streamlit can download it directly
    return bytes(pdf.output())